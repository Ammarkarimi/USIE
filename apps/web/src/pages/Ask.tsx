import { type FormEvent, useEffect, useMemo, useRef, useState } from "react";
import { Link, useNavigate, useParams, useSearchParams } from "react-router-dom";
import { Badge, Button, EmptyState, ErrorBanner, Loading, Spinner, cx, formatDuration, formatRelative } from "@usie/design-system";
import type { AIClaim, AIConversation, AIEvidence, AIMessage, AIStatus } from "@usie/sdk";
import { keyLabel, segmentAnswer } from "@usie/sdk";
import { api } from "../api";
import { useCan } from "../auth";
import { useAsync, useInterval } from "../hooks";
import { PageHeader } from "../App";
import { RepoLinks, VersionPicker, useDocumentTitle, useRepoVersion } from "../components/shared";

/**
 * Questions about an analyzed version, answered by the configured AI
 * provider from knowledge-graph evidence. Every claim shows how it is
 * backed; nothing here is presented as verified fact.
 */
export function AskPage() {
  const { repoId = "" } = useParams();
  const { repo, versions, version, select } = useRepoVersion(repoId);
  const [params, setParams] = useSearchParams();
  const conversationId = params.get("conversation") ?? "";
  const focus = params.get("focus") ?? "";
  const status = useAsync(() => api.aiStatus(), []);
  const conversations = useAsync(() => api.listConversations({ repository_id: repoId, limit: 100 }), [repoId]);
  useDocumentTitle(`Ask · ${repo.data?.name ?? ""}`);

  const setParam = (k: string, v: string | undefined) => {
    const next = new URLSearchParams(params);
    if (v) next.set(k, v);
    else next.delete(k);
    setParams(next);
  };

  if (repo.error) return <div className="p-6"><ErrorBanner error={repo.error} /></div>;
  if (!repo.data || !versions.data || !status.data) return <Loading />;
  return (
    <div className="flex h-full flex-col">
      <PageHeader title={repo.data.name} subtitle="Ask questions about this repository. Answers are generated by an AI model from evidence collected by the analysis; check the cited code before relying on them." />
      <div className="flex flex-wrap items-center justify-between gap-3 border-b border-border px-6 py-2">
        <RepoLinks repoId={repoId} versionId={version?.id} active="ask" />
        <VersionPicker versions={versions.data} value={version?.id} onChange={select} />
      </div>
      {!status.data.enabled ? (
        <EmptyState title="AI answers are not enabled on this installation">
          An administrator can enable them by configuring an AI provider (set <code className="font-mono">OPENAI_API_KEY</code> for the API service).
        </EmptyState>
      ) : (
        <div className="grid min-h-0 flex-1 grid-cols-[16rem_1fr]">
          <aside className="min-h-0 overflow-auto border-r border-border bg-surface" aria-label="Conversations">
            <div className="p-2">
              <Button className="w-full" variant={conversationId ? "secondary" : "primary"} onClick={() => setParam("conversation", undefined)}>
                New conversation
              </Button>
            </div>
            <ErrorBanner error={conversations.error} />
            <ul className="space-y-0.5 px-2 pb-2">
              {(conversations.data ?? []).map((c) => (
                <li key={c.id}>
                  <button
                    type="button"
                    onClick={() => setParam("conversation", c.id)}
                    aria-current={c.id === conversationId ? "page" : undefined}
                    className={cx("w-full rounded-md px-2 py-1.5 text-left text-sm", c.id === conversationId ? "bg-accent/10 text-accent" : "hover:bg-surface-2")}
                  >
                    <span className="line-clamp-2">{c.title}</span>
                    <span className="block text-xs text-muted">{formatRelative(c.updated_at)}</span>
                  </button>
                </li>
              ))}
              {conversations.data?.length === 0 && <li className="px-2 py-1 text-xs text-muted">No conversations yet.</li>}
            </ul>
          </aside>
          <section className="flex min-h-0 min-w-0 flex-col">
            {conversationId ? (
              <ConversationView
                key={conversationId}
                id={conversationId}
                repoId={repoId}
                status={status.data}
                focus={focus}
                onClearFocus={() => setParam("focus", undefined)}
                onChanged={conversations.reload}
                onDeleted={() => {
                  conversations.reload();
                  setParam("conversation", undefined);
                }}
              />
            ) : version ? (
              <NewConversation
                versionId={version.id}
                status={status.data}
                focus={focus}
                onClearFocus={() => setParam("focus", undefined)}
                onCreated={(c) => {
                  conversations.reload();
                  const next = new URLSearchParams(params);
                  next.set("conversation", c.id);
                  next.set("version", c.version_id);
                  setParams(next);
                }}
              />
            ) : (
              <EmptyState title="No analyzed version">Analyze the repository before asking questions about it.</EmptyState>
            )}
          </section>
        </div>
      )}
    </div>
  );
}

function DataNotice({ status }: { status: AIStatus }) {
  const budget = status.daily_token_budget;
  return (
    <p className="text-xs text-muted">
      {status.data_notice}
      {budget > 0 && (
        <> Organization usage today: {status.tokens_used_today.toLocaleString()} of {budget.toLocaleString()} tokens.</>
      )}
    </p>
  );
}

function FocusChip({ focus, onClear }: { focus: string; onClear: () => void }) {
  if (!focus) return null;
  return (
    <div className="flex items-center gap-2 text-xs">
      <span className="text-muted">About:</span>
      <Badge tone="accent">{keyLabel(focus)}</Badge>
      <button type="button" className="text-muted hover:text-fg" onClick={onClear} aria-label="Remove focus">
        ×
      </button>
    </div>
  );
}

function QuestionBox({ onAsk, disabled, placeholder, focus, onClearFocus, autoFocus = false, initial = "" }: { onAsk: (q: string) => Promise<void>; disabled?: boolean; placeholder: string; focus: string; onClearFocus: () => void; autoFocus?: boolean; initial?: string }) {
  const [question, setQuestion] = useState(initial);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<unknown>(null);
  useEffect(() => {
    setQuestion(initial);
  }, [initial]);
  async function submit(e: FormEvent) {
    e.preventDefault();
    if (!question.trim()) return;
    setBusy(true);
    setError(null);
    try {
      await onAsk(question.trim());
      setQuestion("");
    } catch (err) {
      setError(err);
    } finally {
      setBusy(false);
    }
  }
  return (
    <form onSubmit={submit} className="space-y-2">
      <ErrorBanner error={error} />
      <FocusChip focus={focus} onClear={onClearFocus} />
      <textarea
        aria-label="Question"
        value={question}
        onChange={(e) => setQuestion(e.target.value)}
        onKeyDown={(e) => {
          if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) void submit(e);
        }}
        maxLength={4000}
        rows={3}
        autoFocus={autoFocus}
        disabled={disabled}
        placeholder={placeholder}
        className="w-full resize-y rounded-md border border-border bg-surface px-3 py-2 text-sm text-fg placeholder:text-muted focus:border-accent focus:outline-none focus:ring-2 focus:ring-accent/30 disabled:opacity-60"
      />
      <div className="flex items-center justify-between gap-2">
        <span className="text-xs text-muted">Ctrl/⌘ + Enter to send</span>
        <Button type="submit" variant="primary" busy={busy} disabled={disabled || !question.trim()}>
          Ask
        </Button>
      </div>
    </form>
  );
}

const examples = [
  "What does this project do, and where is its entry point?",
  "Which functions call the database layer?",
  "What would be affected if I changed the signature of this function?",
];

function NewConversation({ versionId, status, focus, onClearFocus, onCreated }: { versionId: string; status: AIStatus; focus: string; onClearFocus: () => void; onCreated: (c: AIConversation) => void }) {
  const canAsk = useCan("member");
  const [prefill, setPrefill] = useState("");
  return (
    <div className="mx-auto w-full max-w-3xl space-y-4 overflow-auto p-6">
      <h2 className="text-base font-semibold">New conversation</h2>
      {canAsk ? (
        <>
          <QuestionBox
            autoFocus
            initial={prefill}
            focus={focus}
            onClearFocus={onClearFocus}
            placeholder={focus ? "Ask about the selected code…" : "Ask a question about this repository…"}
            onAsk={async (q) => onCreated(await api.ask({ version_id: versionId, question: q, focus_key: focus || undefined }))}
          />
          {!focus && (
            <div className="flex flex-wrap gap-2">
              {examples.map((e) => (
                <button key={e} type="button" onClick={() => setPrefill(e)} className="rounded-full border border-border px-3 py-1 text-xs text-muted hover:bg-surface-2 hover:text-fg">
                  {e}
                </button>
              ))}
            </div>
          )}
        </>
      ) : (
        <p className="text-sm text-muted">Your role can read conversations but not ask questions.</p>
      )}
      <DataNotice status={status} />
      <HowItWorks />
    </div>
  );
}

function HowItWorks() {
  return (
    <details className="rounded-md border border-border bg-surface p-3 text-sm">
      <summary className="cursor-pointer font-medium">How answers are produced</summary>
      <ul className="mt-2 list-disc space-y-1 pl-5 text-muted">
        <li>USIE collects evidence from the analyzed version: the selected symbol and its neighbours, symbols and files named in the question, or the README and file list for broad questions.</li>
        <li>The model must cite evidence items for each claim. USIE checks every citation; a claim that cites nothing that was provided is marked <em>unsupported</em>.</li>
        <li>Claims the model marks as its own conclusions are shown as <em>inference</em>.</li>
        <li>Repository text is passed as data. Instructions written in the code are not followed, and the model cannot change anything.</li>
        <li>The exact evidence sent with each answer is shown under the answer.</li>
      </ul>
    </details>
  );
}

function ConversationView({ id, repoId, status, focus, onClearFocus, onChanged, onDeleted }: { id: string; repoId: string; status: AIStatus; focus: string; onClearFocus: () => void; onChanged: () => void; onDeleted: () => void }) {
  const conv = useAsync(() => api.getConversation(id), [id]);
  const canAsk = useCan("member");
  const navigate = useNavigate();
  const pending = conv.data?.messages?.some((m) => m.status === "pending") ?? false;
  useInterval(conv.reload, 1500, pending);
  const bottom = useRef<HTMLDivElement>(null);
  const count = conv.data?.messages?.length ?? 0;
  // Block body: an effect must not return what scrollIntoView returns
  // (a promise in some engines), or React would call it as a cleanup.
  useEffect(() => {
    bottom.current?.scrollIntoView({ block: "end" });
  }, [count, pending]);
  const [deleteError, setDeleteError] = useState<unknown>(null);

  if (conv.error && !conv.data) return <div className="p-6"><ErrorBanner error={conv.error} onRetry={conv.reload} /></div>;
  if (!conv.data) return <Loading />;
  const messages = conv.data.messages ?? [];
  const lastFollowups = [...messages].reverse().find((m) => m.role === "assistant" && m.status === "ok")?.answer.followups ?? [];
  const versionId = conv.data.version_id;

  return (
    <>
      <div className="flex items-center justify-between gap-2 border-b border-border px-6 py-2">
        <h2 className="truncate text-sm font-semibold" title={conv.data.title}>{conv.data.title}</h2>
        <div className="flex items-center gap-2">
          <Link className="text-xs text-accent hover:underline" to={`/repositories/${repoId}?version=${versionId}`}>Asked about this version</Link>
          {canAsk && (
            <Button
              size="sm"
              variant="ghost"
              onClick={() => {
                if (window.confirm("Delete this conversation?")) void api.deleteConversation(id).then(onDeleted, setDeleteError);
              }}
            >
              Delete
            </Button>
          )}
        </div>
      </div>
      <ErrorBanner error={deleteError} />
      <div className="min-h-0 flex-1 overflow-auto">
        <div className="mx-auto max-w-3xl space-y-6 p-6">
          {messages.map((m) =>
            m.role === "user" ? (
              <div key={m.id} className="ml-12 rounded-lg bg-accent/10 px-4 py-3 text-sm">
                {m.focus_key && <div className="mb-1 text-xs text-muted">About {keyLabel(m.focus_key)}</div>}
                <p className="whitespace-pre-wrap">{m.content}</p>
              </div>
            ) : (
              <AnswerView key={m.id} m={m} repoId={repoId} versionId={versionId} onFocus={(key) => navigate(`/repositories/${repoId}/graph?version=${versionId}&key=${encodeURIComponent(key)}`)} />
            ),
          )}
          <div ref={bottom} />
        </div>
      </div>
      {canAsk && (
        <div className="border-t border-border bg-surface px-6 py-3">
          <div className="mx-auto max-w-3xl space-y-2">
            {!pending && lastFollowups.length > 0 && (
              <FollowupChips items={lastFollowups} onPick={(q) => void api.askFollowup(id, { question: q, focus_key: focus || undefined }).then(() => { conv.reload(); onChanged(); })} />
            )}
            <QuestionBox
              disabled={pending}
              focus={focus}
              onClearFocus={onClearFocus}
              placeholder={pending ? "Waiting for the answer…" : "Ask a follow-up question…"}
              onAsk={async (q) => {
                await api.askFollowup(id, { question: q, focus_key: focus || undefined });
                conv.reload();
                onChanged();
              }}
            />
            <DataNotice status={status} />
          </div>
        </div>
      )}
    </>
  );
}

function FollowupChips({ items, onPick }: { items: string[]; onPick: (q: string) => void }) {
  return (
    <div className="flex flex-wrap gap-2" aria-label="Suggested follow-up questions">
      {items.slice(0, 3).map((q) => (
        <button key={q} type="button" onClick={() => onPick(q)} className="rounded-full border border-border px-3 py-1 text-left text-xs text-muted hover:bg-surface-2 hover:text-fg">
          {q}
        </button>
      ))}
    </div>
  );
}

const supportStyle: Record<AIClaim["support"], { label: string; tone: "ok" | "warn" | "danger"; title: string }> = {
  evidence: { label: "cited", tone: "ok", title: "The model says the cited evidence shows this, and every citation refers to evidence that was provided. Open the citations to check." },
  inference: { label: "inference", tone: "warn", title: "The model's own conclusion beyond what the evidence directly shows." },
  unsupported: { label: "unsupported", tone: "danger", title: "Presented as evidence-based, but it cites no evidence that was provided. Treat it as unverified." },
};

function AnswerView({ m, repoId, versionId, onFocus }: { m: AIMessage; repoId: string; versionId: string; onFocus: (key: string) => void }) {
  const evidence = useMemo(() => new Map(m.context.map((e) => [e.id, e])), [m.context]);
  const [open, setOpen] = useState<string | null>(null);
  const codeHref = (e: AIEvidence) =>
    e.path ? `/repositories/${repoId}/code?version=${versionId}&path=${encodeURIComponent(e.path)}${e.start_line ? `&line=${e.start_line}` : ""}` : undefined;
  const cite = (cid: string) => {
    const e = evidence.get(cid);
    if (!e) return <span key={cid} className="text-xs text-danger" title="Not part of the evidence that was provided">[{cid}?]</span>;
    return (
      <button key={cid} type="button" onClick={() => setOpen(open === cid ? null : cid)} title={e.title} className="mx-0.5 rounded bg-surface-2 px-1 font-mono text-xs text-accent hover:underline">
        {cid}
      </button>
    );
  };

  if (m.status === "pending") {
    return (
      <div className="flex items-center gap-2 text-sm text-muted" role="status">
        <Spinner /> Collecting evidence and asking {m.model || "the AI provider"}…
      </div>
    );
  }
  if (m.status !== "ok") {
    return (
      <div role="alert" className="rounded-md border border-danger/40 bg-danger/10 px-4 py-3 text-sm text-danger">
        {m.status === "refused" ? "The AI provider declined to answer this question." : `No answer: ${m.error || "unknown error"}`}
      </div>
    );
  }
  const a = m.answer;
  return (
    <article className="space-y-3 rounded-lg border border-border bg-surface px-4 py-3">
      <header className="flex flex-wrap items-center gap-2 text-xs">
        <Badge tone="info">AI-generated</Badge>
        {a.answerable === "partially" && <Badge tone="warn">partial answer</Badge>}
        {a.answerable === "no" && <Badge tone="danger">the evidence does not answer this</Badge>}
      </header>
      <p className="whitespace-pre-wrap text-sm leading-relaxed">
        {segmentAnswer(a.summary ?? "").map((s, i) =>
          s.type === "text" ? <span key={i}>{s.text}</span> : s.type === "code" ? <code key={i} className="rounded bg-surface-2 px-1 font-mono text-[0.85em]">{s.text}</code> : cite(s.id),
        )}
      </p>
      {open && evidence.get(open) && <EvidenceItem e={evidence.get(open)!} href={codeHref(evidence.get(open)!)} onFocus={onFocus} initiallyOpen />}
      {(a.claims ?? []).length > 0 && (
        <ul className="space-y-1.5 text-sm">
          {a.claims!.map((c, i) => {
            const st = supportStyle[c.support];
            return (
              <li key={i} className={cx("flex gap-2", c.support === "unsupported" && "opacity-80")}>
                <span title={st.title} className="shrink-0"><Badge tone={st.tone}>{st.label}</Badge></span>
                <span>
                  {segmentAnswer(c.statement).map((s, j) => (s.type === "code" ? <code key={j} className="rounded bg-surface-2 px-1 font-mono text-[0.85em]">{s.text}</code> : s.type === "citation" ? cite(s.id) : <span key={j}>{s.text}</span>))}
                  {c.citations.map(cite)}
                  {(c.invalid_citations ?? []).length > 0 && <span className="ml-1 text-xs text-danger">(cited missing evidence: {c.invalid_citations!.join(", ")})</span>}
                </span>
              </li>
            );
          })}
        </ul>
      )}
      {(a.limitations ?? []).length > 0 && (
        <div className="rounded-md border border-warn/40 bg-warn/10 px-3 py-2 text-sm">
          <div className="text-xs font-semibold text-warn">Limitations</div>
          <ul className="mt-1 list-disc pl-5">{a.limitations!.map((l, i) => <li key={i}>{l}</li>)}</ul>
        </div>
      )}
      {(a.validation_notes ?? []).length > 0 && (
        <div className="text-xs text-danger">{a.validation_notes!.map((n, i) => <p key={i}>Check: {n}.</p>)}</div>
      )}
      <details className="text-sm">
        <summary className="cursor-pointer text-xs text-muted">Evidence sent with this question ({m.context.length} items)</summary>
        <div className="mt-2 space-y-2">
          {m.context.map((e) => <EvidenceItem key={e.id} e={e} href={codeHref(e)} onFocus={onFocus} />)}
        </div>
      </details>
      <footer className="text-xs text-muted">
        {m.model} · {(m.input_tokens + m.cache_read_tokens).toLocaleString()} input / {m.output_tokens.toLocaleString()} output tokens · {formatDuration(m.latency_ms)}
      </footer>
    </article>
  );
}

function EvidenceItem({ e, href, onFocus, initiallyOpen = false }: { e: AIEvidence; href?: string; onFocus: (key: string) => void; initiallyOpen?: boolean }) {
  return (
    <details open={initiallyOpen} className="rounded-md border border-border">
      <summary className="flex cursor-pointer flex-wrap items-center gap-2 px-3 py-1.5 text-xs">
        <span className="font-mono font-semibold">{e.id}</span>
        <Badge>{e.kind.replace("_", " ")}</Badge>
        <span className="truncate">{e.title}</span>
        {href && (
          <Link className="text-accent hover:underline" to={href} onClick={(ev) => ev.stopPropagation()}>
            {e.path}{e.start_line ? `:${e.start_line}-${e.end_line}` : ""}
          </Link>
        )}
        {e.key && (e.kind === "symbol" || e.kind === "file") && (
          <button type="button" className="text-accent hover:underline" onClick={(ev) => { ev.preventDefault(); onFocus(e.key!); }}>
            graph
          </button>
        )}
        {e.truncated && <span className="text-warn">shortened</span>}
      </summary>
      <pre className="max-h-80 overflow-auto border-t border-border bg-surface-2 px-3 py-2 font-mono text-xs leading-relaxed">{e.content}</pre>
    </details>
  );
}
