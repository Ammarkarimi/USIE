#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted() {
        for (name, table) in [
            ("PYTHON_BUILTINS", PYTHON_BUILTINS),
            ("ECMASCRIPT_GLOBALS", ECMASCRIPT_GLOBALS),
            ("PYTHON_STDLIB", PYTHON_STDLIB),
            ("NODE_BUILTINS", NODE_BUILTINS),
            ("UBIQUITOUS_METHODS", UBIQUITOUS_METHODS),
            ("GO_BUILTINS", GO_BUILTINS),
            ("JAVA_LANG", JAVA_LANG),
            ("JDK_JAVAX", JDK_JAVAX),
        ] {
            for pair in table.windows(2) {
                assert!(
                    pair[0] < pair[1],
                    "{name}: {:?} must sort before {:?}",
                    pair[0],
                    pair[1]
                );
            }
        }
    }

    #[test]
    fn lookups() {
        assert!(
            is_python_builtin("print")
                && is_python_builtin("ValueError")
                && !is_python_builtin("requests")
        );
        assert!(is_ecmascript_global("console") && !is_ecmascript_global("lodash"));
        assert!(is_python_stdlib("os") && !is_python_stdlib("numpy"));
        assert!(is_node_builtin("fs") && !is_node_builtin("express"));
        assert!(is_ubiquitous_method("push") && !is_ubiquitous_method("reconcileLedger"));
        assert!(is_go_builtin("len") && is_go_builtin("error") && !is_go_builtin("fmt"));
        assert!(is_java_lang("String") && !is_java_lang("List"));
        assert!(is_jdk_package("java.util") && is_jdk_package("javax.crypto.spec"));
        assert!(!is_jdk_package("javax.servlet") && !is_jdk_package("org.springframework"));
        assert!(is_jdk_package("org.w3c.dom") && !is_jdk_package("javax.cryptox"));
    }
}
