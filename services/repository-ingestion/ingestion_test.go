func TestScan(t *testing.T) {
	root := t.TempDir()
	outside := t.TempDir()
	writeTree(t, outside, map[string]string{"secret.txt": "top secret"})
	writeTree(t, root, map[string]string{
		"src/app.py":          "import os\n\ndef main():\n    pass\n",
		"src/big.py":          strings.Repeat("x = 1\n", 400_000),
		"README.md":           "# hi",
		".gitignore":          "dist/\n*.tmp\n",
		"dist/out.js":         "ignored",
		"notes.tmp":           "ignored",
		"node_modules/x/i.js": "skipped",
		".git/config":         "[core]",
		"web/.gitignore":      "/local.ts\n",
		"web/local.ts":        "ignored",
		"web/index.ts":        "export {}\n",
		"vendor/lib/thing.go": "package lib\n",
		"img/logo.png":        "\x89PNG\x00\x00",
	})
	if err := os.Symlink(filepath.Join(outside, "secret.txt"), filepath.Join(root, "link.txt")); err != nil {
		t.Skip("symlinks unavailable")
	}
	os.Symlink(outside, filepath.Join(root, "linkdir"))

	contents := map[string]string{}
	res, err := Scan(context.Background(), root, bigLimits, func(f File, content []byte) error {
		contents[f.Path] = string(content)
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	byPath := map[string]File{}
	for _, f := range res.Files {
		paths = append(paths, f.Path)
		byPath[f.Path] = f
	}
	want := ".gitignore README.md img/logo.png src/app.py src/big.py vendor/lib/thing.go web/.gitignore web/index.ts"
	if got := strings.Join(paths, " "); got != want {
		t.Fatalf("paths:\n got %s\nwant %s", got, want)
	}
	if res.SkippedSymlinks != 2 {
		t.Errorf("SkippedSymlinks = %d", res.SkippedSymlinks)
	}
	for _, c := range contents {
		if strings.Contains(c, "top secret") {
			t.Fatal("scanner read through a symlink")
		}
	}
	app := byPath["src/app.py"]
	if app.Language != "python" || app.Category != CategorySource || app.Lines != 4 || app.Encoding != "utf-8" || len(app.ContentHash) != 64 || app.Oversize {
		t.Errorf("app.py: %+v", app)
	}
	if big := byPath["src/big.py"]; !big.Oversize || big.Size != 2_400_000 || contents["src/big.py"] != "" || len(big.ContentHash) != 64 {
		t.Errorf("big.py: %+v", big)
	}
	if !byPath["vendor/lib/thing.go"].Vendored || byPath["img/logo.png"].Category != CategoryAsset {
		t.Error("vendored/asset flags")
	}

	// The tree hash is content-defined and order-independent.
	again, _ := Scan(context.Background(), root, bigLimits, nil)
	if again.TreeHash != res.TreeHash || len(res.TreeHash) != 64 {
		t.Error("tree hash not stable")
	}
	os.WriteFile(filepath.Join(root, "README.md"), []byte("# changed"), 0o644)
	changed, _ := Scan(context.Background(), root, bigLimits, nil)
	if changed.TreeHash == res.TreeHash {
		t.Error("tree hash did not change with content")
	}

	// Limits fail loudly.
	if _, err := Scan(context.Background(), root, ScanLimits{MaxFiles: 3, MaxBytes: 1 << 30, MaxFileBytes: 1 << 20}, nil); !errors.Is(err, ErrLimit) {
		t.Errorf("file limit: %v", err)
	}
	if _, err := Scan(context.Background(), root, ScanLimits{MaxFiles: 100, MaxBytes: 1000, MaxFileBytes: 1 << 20}, nil); !errors.Is(err, ErrLimit) {
		t.Errorf("byte limit: %v", err)
	}
	ctx, cancel := context.WithCancel(context.Background())
	cancel()
	if _, err := Scan(ctx, root, bigLimits, nil); !errors.Is(err, context.Canceled) {
		t.Errorf("cancel: %v", err)
	}
}

