func TestGeneratedAndEncoding(t *testing.T) {
	if !IsGenerated("api.pb.go", nil) || !IsGenerated("yarn.lock", nil) || !IsGenerated("a.min.js", nil) {
		t.Error("name-based detection")
	}
	if !IsGenerated("x.go", []byte("// Code generated by protoc. DO NOT EDIT.\npackage x\n")) {
		t.Error("header detection")
	}
	if IsGenerated("x.go", []byte("package x\n// regular code\n")) {
		t.Error("false positive")
	}
	if !IsGenerated("bundle.js", []byte(strings.Repeat("a=1;", 5000))) {
		t.Error("minified detection")
	}
	cases := []struct {
		content []byte
		want    string
	}{
		{nil, "utf-8"}, {[]byte("héllo"), "utf-8"}, {[]byte{0xEF, 0xBB, 0xBF, 'a'}, "utf-8-bom"},
		{[]byte{0xFF, 0xFE, 'a', 0}, "utf-16le"}, {[]byte{0x89, 'P', 'N', 'G', 0, 0, 1}, "binary"},
		{[]byte("caf\xe9 au lait, s'il vous pla\xeet"), "unknown"},
	}
	for _, c := range cases {
		if got := DetectEncoding(c.content); got != c.want {
			t.Errorf("DetectEncoding(%q) = %q, want %q", c.content, got, c.want)
		}
	}
}

