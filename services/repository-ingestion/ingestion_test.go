func TestCheckHostBlocksPrivateAddresses(t *testing.T) {
	ctx := context.Background()
	resolver := func(ips ...string) GitOptions {
		return GitOptions{LookupIP: func(context.Context, string) ([]net.IP, error) {
			var out []net.IP
			for _, ip := range ips {
				out = append(out, net.ParseIP(ip))
			}
			return out, nil
		}}
	}
	for _, ip := range []string{"127.0.0.1", "10.1.2.3", "192.168.0.1", "172.16.5.5", "169.254.169.254", "::1", "fd00::1", "0.0.0.0"} {
		if err := checkHost(ctx, ip, GitOptions{}); err == nil {
			t.Errorf("literal %s should be blocked", ip)
		}
		if err := checkHost(ctx, "evil.example", resolver("93.184.216.34", ip)); err == nil {
			t.Errorf("name resolving to %s should be blocked", ip)
		}
	}
	if err := checkHost(ctx, "ok.example", resolver("93.184.216.34")); err != nil {
		t.Error(err)
	}
	if err := checkHost(ctx, "127.0.0.1", GitOptions{AllowPrivateHosts: true}); err != nil {
		t.Error(err)
	}
	if _, err := Clone(ctx, "https://127.0.0.1/a/b", "", filepath.Join(t.TempDir(), "d"), GitOptions{}); err == nil {
		t.Error("clone from loopback should be refused")
	}
}

func TestReadLocalHead(t *testing.T) {
	root := t.TempDir()
	sha := strings.Repeat("ab", 20)
	writeTree(t, root, map[string]string{".git/HEAD": "ref: refs/heads/main\n", ".git/refs/heads/main": sha + "\n"})
	if s, b := ReadLocalHead(root); s != sha || b != "main" {
		t.Errorf("loose ref: %q %q", s, b)
	}
	os.Remove(filepath.Join(root, ".git/refs/heads/main"))
	writeTree(t, root, map[string]string{".git/packed-refs": "# pack-refs\n" + sha + " refs/heads/main\n"})
	if s, _ := ReadLocalHead(root); s != sha {
		t.Errorf("packed ref: %q", s)
	}
	writeTree(t, root, map[string]string{".git/HEAD": "ref: ../../../etc/passwd\n"})
	if s, b := ReadLocalHead(root); s != "" || b != "" {
		t.Errorf("traversal: %q %q", s, b)
	}
	if s, b := ReadLocalHead(t.TempDir()); s != "" || b != "" {
		t.Error("non-repo")
	}
}

func makeZip(t *testing.T, build func(w *zip.Writer)) *bytes.Reader {
	t.Helper()
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	build(w)
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return bytes.NewReader(buf.Bytes())
}

func TestExtractZip(t *testing.T) {
	ctx := context.Background()
	add := func(w *zip.Writer, name, content string) {
		f, _ := w.Create(name)
		f.Write([]byte(content))
	}
	// A wrapped archive (single top-level directory) is unwrapped.
	dest := t.TempDir()
	r := makeZip(t, func(w *zip.Writer) {
		add(w, "repo-main/", "")
		add(w, "repo-main/src/a.py", "print(1)\n")
		add(w, "repo-main/README.md", "# x")
		h := &zip.FileHeader{Name: "repo-main/link"}
		h.SetMode(os.ModeSymlink | 0o777)
		f, _ := w.CreateHeader(h)
		f.Write([]byte("/etc/passwd"))
	})
	n, err := ExtractZip(ctx, r, r.Size(), dest, bigLimits)
	if err != nil || n != 2 {
		t.Fatalf("extract: n=%d err=%v", n, err)
	}
	if data, _ := os.ReadFile(filepath.Join(dest, "src/a.py")); string(data) != "print(1)\n" {
		t.Error("content mismatch")
	}
	if _, err := os.Lstat(filepath.Join(dest, "link")); err == nil {
		t.Error("symlink entry must be skipped")
	}

	for _, name := range []string{"../evil.txt", "a/../../evil.txt", "/abs.txt", "C:/x.txt", "a/./b.txt", "a\\..\\..\\evil.txt"} {
		parent := t.TempDir()
		dest := filepath.Join(parent, "dest")
		os.Mkdir(dest, 0o755)
		r := makeZip(t, func(w *zip.Writer) { add(w, "ok.txt", "ok"); add(w, name, "evil") })
		if _, err := ExtractZip(ctx, r, r.Size(), dest, bigLimits); err == nil {
			t.Errorf("entry %q should be rejected", name)
		}
		if entries, _ := os.ReadDir(parent); len(entries) != 1 {
			t.Errorf("entry %q wrote outside the destination", name)
		}
	}

	// Decompressed size is bounded by bytes actually written.
	bomb := makeZip(t, func(w *zip.Writer) {
		add(w, "a.txt", strings.Repeat("0", 1<<20))
		add(w, "b.txt", strings.Repeat("0", 1<<20))
	})
	if bomb.Size() > 10_000 {
		t.Fatalf("test archive should compress well, got %d bytes", bomb.Size())
	}
	if _, err := ExtractZip(ctx, bomb, bomb.Size(), t.TempDir(), ScanLimits{MaxFiles: 10, MaxBytes: 1 << 20, MaxFileBytes: 1 << 20}); !errors.Is(err, ErrLimit) {
		t.Errorf("zip bomb: %v", err)
	}
	many := makeZip(t, func(w *zip.Writer) { add(w, "a", "1"); add(w, "b", "1"); add(w, "c", "1") })
	if _, err := ExtractZip(ctx, many, many.Size(), t.TempDir(), ScanLimits{MaxFiles: 2, MaxBytes: 1 << 20, MaxFileBytes: 1 << 20}); !errors.Is(err, ErrLimit) {
		t.Errorf("file count: %v", err)
	}
	dup := makeZip(t, func(w *zip.Writer) { add(w, "a", "first"); add(w, "a", "second") })
	if _, err := ExtractZip(ctx, dup, dup.Size(), t.TempDir(), bigLimits); err == nil {
		t.Error("duplicate entries should be rejected")
	}
	garbage := bytes.NewReader([]byte("not a zip"))
	if _, err := ExtractZip(ctx, garbage, garbage.Size(), t.TempDir(), bigLimits); err == nil {
		t.Error("garbage should be rejected")
	}
}

func TestResolveLocalPath(t *testing.T) {
	allowed, _ := filepath.EvalSymlinks(t.TempDir())
	outside, _ := filepath.EvalSymlinks(t.TempDir())
	os.Mkdir(filepath.Join(allowed, "repo"), 0o755)
	os.WriteFile(filepath.Join(allowed, "file"), nil, 0o644)
	os.Symlink(outside, filepath.Join(allowed, "escape"))

	if p, err := ResolveLocalPath(filepath.Join(allowed, "repo"), []string{allowed}); err != nil || p != filepath.Join(allowed, "repo") {
		t.Errorf("valid path: %q %v", p, err)
	}
	for name, loc := range map[string]string{
		"outside": outside, "relative": "repo", "traversal": filepath.Join(allowed, "repo", "..", "..", filepath.Base(outside)),
		"symlink escape": filepath.Join(allowed, "escape"), "file": filepath.Join(allowed, "file"), "missing": filepath.Join(allowed, "nope"),
		"prefix sibling": allowed + "x",
	} {
		if _, err := ResolveLocalPath(loc, []string{allowed}); err == nil {
			t.Errorf("%s: %q should be rejected", name, loc)
		}
	}
	if _, err := ResolveLocalPath(filepath.Join(allowed, "repo"), nil); err == nil {
		t.Error("local import must be disabled without allowed roots")
	}
}
